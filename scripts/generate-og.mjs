/**
 * Generate 1200x630 OG images for blog posts from their existing hero art.
 *
 * - Sequential (one image at a time) to keep memory low on Windows.
 * - Skips sources whose aspect ratio would need a redraw (below MIN_RATIO).
 * - Writes public/images/og/<slug>.jpg (< 300KB) and src/data/blog-og.js
 *   with a slug -> path map for posts that got a dedicated OG image.
 *
 * Usage: node scripts/generate-og.mjs
 */
import { mkdir, writeFile, stat } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { slugToImage, FALLBACK_BLOG_IMAGE } from "../src/data/blog-images.js";

const SITE_ROOT = process.cwd();
const OUT_DIR = path.join(SITE_ROOT, "public", "images", "og");
const OUT_MAP = path.join(SITE_ROOT, "src", "data", "blog-og.js");
const WIDTH = 1200;
const HEIGHT = 630;
const TARGET_RATIO = WIDTH / HEIGHT; // 1.905
const MIN_RATIO = 1.58; // below this, a center crop cuts too much art
const MAX_BYTES = 300 * 1024;
const QUALITIES = [80, 72, 64, 56];

await mkdir(OUT_DIR, { recursive: true });

const rows = [];
const slugToOg = {};

for (const [slug, rel] of Object.entries(slugToImage)) {
  const srcPath = path.join(SITE_ROOT, "public", rel);
  const outName = `${slug}.jpg`;
  const outPath = path.join(OUT_DIR, outName);

  try {
    const meta = await sharp(srcPath).metadata();
    const w = meta.width ?? 0;
    const h = meta.height ?? 0;
    const ratio = h > 0 ? w / h : 0;

    if (!w || !h || ratio < MIN_RATIO) {
      rows.push({
        slug,
        source: `${w}x${h}`,
        output: "—",
        status: `fallback (ratio ${ratio.toFixed(2)} < ${MIN_RATIO}; redraw needed)`,
      });
      continue;
    }

    let bytes = 0;
    for (const quality of QUALITIES) {
      const buf = await sharp(srcPath)
        .resize(WIDTH, HEIGHT, { fit: "cover", position: "centre" })
        .jpeg({ quality, mozjpeg: true })
        .toBuffer();
      bytes = buf.length;
      if (bytes <= MAX_BYTES) {
        await writeFile(outPath, buf);
        break;
      }
    }

    if (bytes > MAX_BYTES) {
      rows.push({
        slug,
        source: `${w}x${h}`,
        output: `${Math.round(bytes / 1024)}KB`,
        status: "fallback (could not get under 300KB)",
      });
      continue;
    }

    const finalSize = (await stat(outPath)).size;
    slugToOg[slug] = `/images/og/${outName}`;
    rows.push({
      slug,
      source: `${w}x${h}`,
      output: `${Math.round(finalSize / 1024)}KB`,
      status: "og",
    });
  } catch (err) {
    rows.push({
      slug,
      source: rel === FALLBACK_BLOG_IMAGE ? "fallback" : "error",
      output: "—",
      status: `fallback (${err.message})`,
    });
  }
}

const mapFile = `// Generated by scripts/generate-og.mjs — do not edit by hand.
// Maps post slug -> dedicated 1200x630 OG image path. Posts missing here
// fall back to /og.jpg.

export const slugToOg = /** @type {Record<string, string>} */ (${JSON.stringify(slugToOg, null, 2)});
`;
await writeFile(OUT_MAP, mapFile);

const pad = (s, n) => String(s).padEnd(n);
console.log(
  `${pad("slug", 52)} ${pad("source", 10)} ${pad("output", 8)} status`,
);
for (const r of rows) {
  console.log(
    `${pad(r.slug, 52)} ${pad(r.source, 10)} ${pad(r.output, 8)} ${r.status}`,
  );
}
const ogCount = rows.filter((r) => r.status === "og").length;
console.log(
  `\n${ogCount} OG images written, ${rows.length - ogCount} fallback. Map: src/data/blog-og.js`,
);
